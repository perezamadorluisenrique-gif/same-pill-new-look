  const LANGS = Object.keys(STRINGS);

  function makeT(lang) {
    const L = STRINGS[lang] ? lang : 'en';
    const t = (key, vars) => {
      let s = STRINGS[L][key];
      if (s === undefined) s = STRINGS.en[key];
      if (s === undefined) return key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
      return s;
    };
    t.lang = L;
    t.word = (w) => (WORDS[L][w] || WORDS.en[w] || w);
    t.date = (d) => {
      try { return new Date(d).toLocaleDateString(L === 'es' ? 'es-US' : 'en-US', { year: 'numeric', month: 'long', day: 'numeric' }); } catch (e) { return String(d); }
    };
    return t;
  }

  function pickLang(navLangs) {
    for (const l of navLangs || []) {
      const base = String(l).toLowerCase().slice(0, 2);
      if (LANGS.includes(base)) return base;
    }
    return 'en';
  }

